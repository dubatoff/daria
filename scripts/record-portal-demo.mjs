import { createRequire } from "node:module";
import fs from "node:fs/promises";
import path from "node:path";
const runtimeRequire=createRequire("C:/Users/dubat/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.js");
const {chromium}=runtimeRequire("playwright");
const out=path.resolve("artifacts/portal-video");
await fs.mkdir(out,{recursive:true});
const browser=await chromium.launch({headless:true,executablePath:"C:/Program Files/Google/Chrome/Application/chrome.exe"});
const context=await browser.newContext({viewport:{width:1280,height:720},recordVideo:{dir:out,size:{width:1280,height:720}}});
const page=await context.newPage();
await page.goto("http://localhost:4173/",{waitUntil:"networkidle"});
await page.waitForTimeout(5200);
await page.mouse.move(500,115);
await page.waitForTimeout(350);
await page.getByRole("link",{name:"Daria Demian"}).hover();
await page.waitForTimeout(8500);
const video=page.video();
await context.close();await browser.close();
if(!video)throw new Error("Video recording was not created");
const raw=await video.path();
const saved=path.resolve("artifacts/butterfly-portal-demo-raw.webm");
await fs.copyFile(raw,saved);
console.log(saved);
